// RegWrite : Enables writing data into the destination register (rd).

// ALUSrc : Selects the second ALU operand.
//          0 = Register (rs2)
//          1 = Immediate value

// MemRead : Enables reading data from Data Memory (used by load instructions).

// MemWrite : Enables writing data into Data Memory (used by store instructions).

// MemtoReg : Selects the data written back to the Register File.
//             0 = ALU Result
//             1 = Data Memory Output

// Branch : Indicates a branch instruction.
//          Used by PC logic to decide whether to branch.


// Jump : Indicates a jump instruction (JAL/JALR).
//        Used by PC logic to update the Program Counter.


// ALUOp : High-level ALU operation code generated by the Main Control Unit.
//          Sent to the ALU Control Unit for final ALU operation decoding.
//          00 = ADD (Load/Store/Address Calculation)
//          01 = SUB (Branch Comparison)
//          10 = Decode funct3 & funct7 (R-Type/I-Type ALU)
//          11 = Reserved/Special Instructions


module Main_control_unit(
    input [31:0] instruction,
    output reg RegWrite, MemRead, MemWrite, Branch, Jump, ALUSrc, MemtoReg,
    output reg [1:0] ALUOp // tells which operation to be performed.. it will be send to ALU control unit.
    );
    /*
        ALUop values => 
        00 -> Always ADD (load, store, auipc, address calculation)
        01 -> Always SUB (branch comparison)
        10 -> Decode funct3 and funct7 (R-type and I-type ALU instructions)
        11 -> Reserved or future extension
    */
    
    wire [6:0] opcode;
    assign opcode = instruction[6:0];

    always @(*) begin

    // Default Values
    RegWrite = 1'b0;
    ALUSrc   = 1'b0;
    MemRead  = 1'b0;
    MemWrite = 1'b0;
    MemtoReg = 1'b0;
    Branch   = 1'b0;
    Jump     = 1'b0;
    ALUOp    = 2'b00;

    case(opcode)

    //====================================================
    // R-Type (ADD, SUB, AND, OR, XOR, SLL, SRL, SRA, SLT)
    // Opcode = 0110011
    //====================================================
    7'b0110011:
    begin
        RegWrite = 1'b1;
        ALUSrc   = 1'b0;
        MemRead  = 1'b0;
        MemWrite = 1'b0;
        MemtoReg = 1'b0;
        Branch   = 1'b0;
        Jump     = 1'b0;
        ALUOp    = 2'b10;
    end

    //====================================================
    // I-Type ALU (ADDI, ANDI, ORI, XORI, SLTI...)
    // Opcode = 0010011
    //====================================================
    7'b0010011:
    begin
        RegWrite = 1'b1;
        ALUSrc   = 1'b1;
        MemRead  = 1'b0;
        MemWrite = 1'b0;
        MemtoReg = 1'b0;
        Branch   = 1'b0;
        Jump     = 1'b0;
        ALUOp    = 2'b10;
    end

    //====================================================
    // LOAD (LW)
    // Opcode = 0000011
    //====================================================
    7'b0000011:
    begin
        RegWrite = 1'b1;
        ALUSrc   = 1'b1;
        MemRead  = 1'b1;
        MemWrite = 1'b0;
        MemtoReg = 1'b1;
        Branch   = 1'b0;
        Jump     = 1'b0;
        ALUOp    = 2'b00;
    end

    //====================================================
    // STORE (SW)
    // Opcode = 0100011
    //====================================================
    7'b0100011:
    begin
        RegWrite = 1'b0;
        ALUSrc   = 1'b1;
        MemRead  = 1'b0;
        MemWrite = 1'b1;
        MemtoReg = 1'b0;     // Don't Care
        Branch   = 1'b0;
        Jump     = 1'b0;
        ALUOp    = 2'b00;
    end

    //====================================================
    // BRANCH (BEQ, BNE, BLT...)
    // Opcode = 1100011
    //====================================================
    7'b1100011:
    begin
        RegWrite = 1'b0;
        ALUSrc   = 1'b0;
        MemRead  = 1'b0;
        MemWrite = 1'b0;
        MemtoReg = 1'b0;     // Don't Care
        Branch   = 1'b1;
        Jump     = 1'b0;
        ALUOp    = 2'b01;
    end

    //====================================================
    // JAL
    // Opcode = 1101111
    //====================================================
    7'b1101111:
    begin
        RegWrite = 1'b1;
        ALUSrc   = 1'b0;
        MemRead  = 1'b0;
        MemWrite = 1'b0;
        MemtoReg = 1'b0;
        Branch   = 1'b0;
        Jump     = 1'b1;
        ALUOp    = 2'b00;
    end

    //====================================================
    // JALR
    // Opcode = 1100111
    //====================================================
    7'b1100111:
    begin
        RegWrite = 1'b1;
        ALUSrc   = 1'b1;
        MemRead  = 1'b0;
        MemWrite = 1'b0;
        MemtoReg = 1'b0;
        Branch   = 1'b0;
        Jump     = 1'b1;
        ALUOp    = 2'b00;
    end

    //====================================================
    // LUI
    // Opcode = 0110111
    //====================================================
    7'b0110111:
    begin
        RegWrite = 1'b1;
        ALUSrc   = 1'b1;
        MemRead  = 1'b0;
        MemWrite = 1'b0;
        MemtoReg = 1'b0;
        Branch   = 1'b0;
        Jump     = 1'b0;
        ALUOp    = 2'b11;    // Reserved/Special handling
    end

    //====================================================
    // AUIPC
    // Opcode = 0010111
    //====================================================
    7'b0010111:
    begin
        RegWrite = 1'b1;
        ALUSrc   = 1'b1;
        MemRead  = 1'b0;
        MemWrite = 1'b0;
        MemtoReg = 1'b0;
        Branch   = 1'b0;
        Jump     = 1'b0;
        ALUOp    = 2'b00;
    end

    //====================================================
    // Default
    //====================================================
    default:
    begin
        RegWrite = 1'b0;
        ALUSrc   = 1'b0;
        MemRead  = 1'b0;
        MemWrite = 1'b0;
        MemtoReg = 1'b0;
        Branch   = 1'b0;
        Jump     = 1'b0;
        ALUOp    = 2'b00;
    end

    endcase

end
    
    
endmodule
